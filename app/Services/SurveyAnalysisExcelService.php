    /**
     * Calculate the average score submitted by one response.
     */
    private function calculateResponseAverage(
        array $sections,
        int $responseIndex
    ): ?float {
        $values = [];

        foreach ($sections as $section) {
            foreach (
                $section['questions'] ?? [] as
                $question
            ) {
                if (empty($question['is_numeric'])) {
                    continue;
                }

                $response =
                    $question['individual_responses'][$responseIndex]
                    ?? null;

                $value = $response['value'] ?? null;

                if (
                    $value !== null
                    && $value !== ''
                    && is_numeric($value)
                ) {
                    $values[] = (float) $value;
                }
            }
        }

        if (empty($values)) {
            return null;
        }

        return round(
            array_sum($values) / count($values),
            2
        );
    }

    /**
     * Count how many numeric questions were answered
     * by one response.
     */
    private function countResponseAnswers(
        array $sections,
        int $responseIndex
    ): int {
        $count = 0;

        foreach ($sections as $section) {
            foreach (
                $section['questions'] ?? [] as
                $question
            ) {
                if (empty($question['is_numeric'])) {
                    continue;
                }

                $response =
                    $question['individual_responses'][$responseIndex]
                    ?? null;

                $value = $response['value'] ?? null;

                if (
                    $value !== null
                    && $value !== ''
                ) {
