    public function __construct(
        private SurveyAnalysisService $analysisService
    ) {}

    /**
     * Create the complete survey analysis Excel file.
     */
    public function export(Survey $survey): string
    {
        $analysis = $this->analysisService->analyze($survey);

        /*
     * Create a completely new workbook.
     */
        $spreadsheet = new Spreadsheet();

        $spreadsheet->getProperties()
            ->setCreator('Port Said University')
            ->setLastModifiedBy('Port Said University')
            ->setTitle('Course Evaluation Survey Analysis')
            ->setSubject('Course Evaluation Survey Results')
            ->setDescription(
                'Course evaluation survey analysis generated by PSU Surveys System.'
            );

        /*
     * Only one sheet containing:
     *
     * - Survey information
     * - Individual responses
     * - Question statistics
     * - Individual response analysis
     * - Overall result
     * - Respondents comments
     */
        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle('Course Evaluation Survey');

        $this->buildResponsesSheet(
            $sheet,
            $analysis
        );

        $this->buildResponsesSheet(
            $sheet,
            $analysis
        );

        /*
        |--------------------------------------------------------------------------
        | Charts Sheet
        |--------------------------------------------------------------------------
        */
        $chartsSheet = $spreadsheet->createSheet();
        $chartsSheet->setTitle('Charts');

        $this->buildChartsSheet(
            $chartsSheet,
            $analysis
        );

        /*
        |--------------------------------------------------------------------------
        | Keep first sheet active
        |--------------------------------------------------------------------------
        */
        $spreadsheet->setActiveSheetIndex(0);

        $spreadsheet->setActiveSheetIndex(0);

        $directory = storage_path(
            'app/public/survey-analysis'
        );

        if (
            !is_dir($directory)
            && !mkdir($directory, 0755, true)
            && !is_dir($directory)
        ) {
            throw new RuntimeException(
                'Unable to create the survey analysis directory.'
            );
        }

        $fileName = sprintf(
            'course-evaluation-%d-%s.xlsx',
            $survey->id,
            now()->format('Ymd-His')
        );

        $filePath = $directory
            . DIRECTORY_SEPARATOR
            . $fileName;

        $writer = new Xlsx($spreadsheet);

        /*
 * Important:
 * Save charts inside the generated Excel file.
 */
        $writer->setIncludeCharts(true);

        /*
 * Laravel writes calculated values only.
 * No Excel formulas are used.
 */
        $writer->setPreCalculateFormulas(false);

        $writer->save($filePath);

        $spreadsheet->disconnectWorksheets();

        unset($spreadsheet);

        return $filePath;
    }

    /**
     * Build the detailed survey responses sheet.
     */
    /**
     * Build the detailed responses sheet.
     *
     * Each survey response is displayed in a separate column,
     * following the same general structure as the reference file.
     */
    private function buildResponsesSheet(
        Worksheet $sheet,
        array $analysis
    ): void {
        $sheet->setRightToLeft(true);
        $sheet->setShowGridlines(false);

        $surveyData = $analysis['survey'] ?? [];
        $responses = array_values($analysis['responses'] ?? []);
        $sections = $analysis['sections'] ?? [];

        $responsesCount = count($responses);

        /*
         * Columns:
         *
         * A      No.
         * B:H    Evaluation item
         * I:J    Section
         * K      Question code
         * L...   Individual responses
         * Next   Class Average
         * Next   # Respondents Exceeding Criteria
         * Next   % Respondents Exceeding Criteria
         * Next   Section Average
         */

        $numberColumn = 1;             // A
        $questionStartColumn = 2;      // B
        $questionEndColumn = 8;        // H
        $sectionStartColumn = 9;       // I
        $sectionEndColumn = 10;        // J
        $questionCodeColumn = 11;      // K
        $responsesStartColumn = 12;    // L

        /*
         * Keep at least one response column.
         */
        $lastResponseColumnIndex = $responsesCount > 0
            ? $responsesStartColumn + $responsesCount - 1
            : $responsesStartColumn;

        $averageColumn = $lastResponseColumnIndex + 1;
        $exceedingColumn = $lastResponseColumnIndex + 2;
        $percentageColumn = $lastResponseColumnIndex + 3;
        $sectionAverageColumn = $lastResponseColumnIndex + 4;

        $lastColumn = $this->columnLetter(
            $sectionAverageColumn
        );

        $averageColumnLetter = $this->columnLetter(
            $averageColumn
        );

        $exceedingColumnLetter = $this->columnLetter(
            $exceedingColumn
        );

        $percentageColumnLetter = $this->columnLetter(
            $percentageColumn
        );

        $sectionAverageColumnLetter = $this->columnLetter(
            $sectionAverageColumn
        );

        /*
         * General font.
         */
        $sheet->getParent()
            ->getDefaultStyle()
            ->getFont()
            ->setName('Arial')
            ->setSize(10);

        /*
         * Header area.
         */
        $sheet->mergeCells('B1:H1');
        $sheet->mergeCells('B2:H2');
        $sheet->mergeCells('B3:H3');
        $sheet->mergeCells('B4:H4');
        $sheet->mergeCells('B5:H5');

        $sheet->setCellValue(
            'B1',
            'نتيجة استطلاع رأي حول مقرر دراسي'
        );

        $academicYear = $surveyData['academic_year'] ?? '-';
        $semester = $this->semesterArabicLabel(
            $surveyData['semester'] ?? null
        );

        $sheet->setCellValue(
            'B2',
            "العام الدراسي: {$academicYear}    الفصل الدراسي: {$semester}"
        );

        $sheet->setCellValue(
            'B3',
            'القسم: ' . ($surveyData['department'] ?? '-')
                . '    المستوى: '
                . ($surveyData['level'] ?? '-')
        );

        $sheet->setCellValue(
            'B4',
            'اسم المقرر: '
                . (
                    $surveyData['course']
                    ?? $surveyData['title']
                    ?? '-'
                )
        );

        $sheet->setCellValue(
            'B5',
            'الكلية: '
                . ($surveyData['faculty'] ?? '-')
        );

        $sheet->getStyle('B1:H1')->applyFromArray([
            'font' => [
                'bold' => true,
                'size' => 15,
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
            ],
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_MEDIUM,
                    'color' => ['rgb' => '000000'],
                ],
            ],
        ]);

        $sheet->getStyle('B2:H5')->applyFromArray([
            'font' => [
                'bold' => true,
                'size' => 10,
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_RIGHT,
                'vertical' => Alignment::VERTICAL_CENTER,
                'wrapText' => true,
            ],
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_THIN,
                    'color' => ['rgb' => '000000'],
                ],
            ],
        ]);

        /*
         * Logo areas.
         */
        $sheet->mergeCells('A1:A5');
        $sheet->mergeCells('I1:J5');

        // $this->addReportLogo(
        //     $sheet,
        //     public_path('images/psu-logo.png'),
        //     'A1',
        //     65
        // );

        // $this->addReportLogo(
        //     $sheet,
        //     public_path('images/quality-logo.png'),
        //     'I1',
        //     70
        // );

        /*
         * Survey statistics.
         */
        $statisticsLabelStart = $questionCodeColumn;
        $statisticsLabelEnd = $questionCodeColumn + 2;
        $statisticsValueColumn = $questionCodeColumn + 3;

        $statisticsLabelStartLetter = $this->columnLetter(
            $statisticsLabelStart
        );

        $statisticsLabelEndLetter = $this->columnLetter(
            $statisticsLabelEnd
        );

        $statisticsValueColumnLetter = $this->columnLetter(
            $statisticsValueColumn
        );

        for ($row = 1; $row <= 3; $row++) {
            $sheet->mergeCells(
                "{$statisticsLabelStartLetter}{$row}:"
                    . "{$statisticsLabelEndLetter}{$row}"
            );
        }

        $sheet->setCellValue(
            "{$statisticsLabelStartLetter}1",
            'عدد أسئلة الاستبيان'
        );

        $sheet->setCellValue(
            "{$statisticsValueColumnLetter}1",
            $this->countNumericQuestions($sections)
        );

        $sheet->setCellValue(
            "{$statisticsLabelStartLetter}2",
            'عدد الجهات التي أجابت'
        );

        $sheet->setCellValue(
            "{$statisticsValueColumnLetter}2",
            $responsesCount
        );

        $threshold = (float) (
            $analysis['settings']['satisfaction_threshold']
            ?? 3
        );

        $sheet->setCellValue(
            "{$statisticsLabelStartLetter}3",
            'معيار المرور'
        );

        $sheet->setCellValue(
            "{$statisticsValueColumnLetter}3",
            $threshold
        );

        $sheet->getStyle(
            "{$statisticsLabelStartLetter}1:"
                . "{$statisticsValueColumnLetter}3"
        )->applyFromArray([
            'font' => [
                'bold' => true,
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
                'wrapText' => true,
            ],
            'fill' => [
                'fillType' => Fill::FILL_SOLID,
                'startColor' => [
                    'rgb' => 'C69AF4',
                ],
            ],
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_MEDIUM,
                    'color' => ['rgb' => '000000'],
                ],
            ],
        ]);

        /*
         * Response scale.
         *
         * This is independent of the number of submitted responses.
         * Therefore all five scale options always appear.
         */
        $scaleHeaderRow = 6;
        $scaleValuesRow = 7;

        $sheet->mergeCells(
            "A{$scaleHeaderRow}:H{$scaleValuesRow}"
        );

        $sheet->setCellValue(
            "A{$scaleHeaderRow}",
            'عناصر الاستبانة'
        );

        $sheet->getStyle(
            "A{$scaleHeaderRow}:H{$scaleValuesRow}"
        )->applyFromArray([
            'font' => [
                'bold' => true,
                'size' => 18,
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
            ],
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_MEDIUM,
                    'color' => ['rgb' => '000000'],
                ],
            ],
        ]);

        /*
         * Scale uses five fixed columns I:M.
         */
        $scaleStartColumn = 9;

        $scaleLabels = [
            1 => 'غير موافق بشدة',
            2 => 'غير موافق',
            3 => 'محايد',
            4 => 'موافق',
            5 => 'موافق بشدة',
        ];

        foreach ($scaleLabels as $value => $label) {
            $columnIndex = $scaleStartColumn + $value - 1;
            $column = $this->columnLetter($columnIndex);

            $sheet->setCellValue(
                "{$column}{$scaleHeaderRow}",
                $value
            );

            $sheet->setCellValue(
                "{$column}{$scaleValuesRow}",
                $label
            );

            $sheet->getStyle(
                "{$column}{$scaleValuesRow}"
            )->getAlignment()
                ->setTextRotation(90);
        }

        $scaleEndColumn = $this->columnLetter(
            $scaleStartColumn + 4
        );

        $sheet->getStyle(
            "I{$scaleHeaderRow}:{$scaleEndColumn}{$scaleValuesRow}"
        )->applyFromArray([
            'font' => [
                'bold' => true,
                'size' => 9,
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
                'wrapText' => true,
            ],
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_MEDIUM,
                    'color' => ['rgb' => '000000'],
                ],
            ],
        ]);

        /*
         * Table header.
         */
        $headerRow = 8;

        $sheet->setCellValue("A{$headerRow}", 'م');
        $sheet->mergeCells("B{$headerRow}:H{$headerRow}");
        $sheet->setCellValue("B{$headerRow}", 'عنصر التقييم');

        $sheet->mergeCells("I{$headerRow}:J{$headerRow}");
        $sheet->setCellValue("I{$headerRow}", 'المحور');

        $sheet->setCellValue("K{$headerRow}", 'السؤال');

        foreach ($responses as $responseIndex => $response) {
            $columnIndex = $responsesStartColumn + $responseIndex;
            $column = $this->columnLetter($columnIndex);

            $sheet->setCellValue(
                "{$column}{$headerRow}",
                '#' . ($responseIndex + 1)
            );
        }

        if ($responsesCount === 0) {
            $column = $this->columnLetter(
                $responsesStartColumn
            );

            $sheet->setCellValue(
                "{$column}{$headerRow}",
                '#1'
            );
        }

        $sheet->setCellValue(
            "{$averageColumnLetter}{$headerRow}",
            "Class\nAverage"
        );

        $sheet->setCellValue(
            "{$exceedingColumnLetter}{$headerRow}",
            "# respondents\nExceeding\nCriteria"
        );

        $sheet->setCellValue(
            "{$percentageColumnLetter}{$headerRow}",
            "% of\nrespondents\nExceeding\nCriteria"
        );

        $sheet->setCellValue(
            "{$sectionAverageColumnLetter}{$headerRow}",
            'متوسط المحور'
        );

        $sheet->getStyle(
            "A{$headerRow}:{$lastColumn}{$headerRow}"
        )->applyFromArray([
            'font' => [
                'bold' => true,
                'color' => [
                    'rgb' => '000000',
                ],
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
                'wrapText' => true,
            ],
            'fill' => [
                'fillType' => Fill::FILL_SOLID,
                'startColor' => [
                    'rgb' => 'A6A6A6',
                ],
            ],
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_MEDIUM,
                    'color' => ['rgb' => '000000'],
                ],
            ],
        ]);

        $sheet->getStyle(
            "{$averageColumnLetter}{$headerRow}:"
                . "{$percentageColumnLetter}{$headerRow}"
        )->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()
            ->setRGB('4BACC6');

        $sheet->getRowDimension($headerRow)
            ->setRowHeight(65);

        /*
         * Question rows.
         */
        $currentRow = $headerRow + 1;
        $questionRows = [];

        foreach ($sections as $sectionIndex => $section) {
            $sectionStartRow = $currentRow;
            $sectionQuestionRows = [];

            foreach (
                $section['questions'] ?? []
                as $questionIndex => $question
            ) {
                $number = $question['number']
                    ?? count($questionRows) + 1;

                $sheet->setCellValue(
                    "A{$currentRow}",
                    $number
                );

                $sheet->mergeCells(
                    "B{$currentRow}:H{$currentRow}"
                );

                $sheet->setCellValue(
                    "B{$currentRow}",
                    $question['text'] ?? ''
                );

                $sheet->setCellValue(
                    "K{$currentRow}",
                    'Q' . $number
                );

                foreach (
                    $question['individual_responses'] ?? []
                    as $responseIndex => $individualResponse
                ) {
                    $columnIndex = $responsesStartColumn
                        + $responseIndex;

                    if (
                        $columnIndex
                        > $lastResponseColumnIndex
                    ) {
                        continue;
                    }

                    $column = $this->columnLetter(
                        $columnIndex
                    );

                    $value = !empty($question['is_numeric'])
                        ? ($individualResponse['value'] ?? null)
                        : ($individualResponse['text'] ?? null);

                    $sheet->setCellValue(
                        "{$column}{$currentRow}",
                        $value
                    );
                }

                $statistics = $question['statistics'] ?? [];

                if (!empty($question['is_numeric'])) {
                    $average = $statistics['average'] ?? null;

                    $satisfiedCount =
                        $statistics['satisfied_count'] ?? 0;

                    $satisfactionPercentage =
                        $statistics['satisfaction_percentage']
                        ?? null;

                    $sheet->setCellValue(
                        "{$averageColumnLetter}{$currentRow}",
                        $average
                    );

                    $sheet->setCellValue(
                        "{$exceedingColumnLetter}{$currentRow}",
                        $satisfiedCount
                    );

                    $sheet->setCellValue(
                        "{$percentageColumnLetter}{$currentRow}",
                        is_numeric($satisfactionPercentage)
                            ? $satisfactionPercentage / 100
                            : null
                    );
                }

                $rowFill = $questionIndex % 2 === 0
                    ? 'F8CBAD'
                    : 'FFFFFF';

                $sheet->getStyle(
                    "A{$currentRow}:{$lastColumn}{$currentRow}"
                )->applyFromArray([
                    'alignment' => [
                        'horizontal' => Alignment::HORIZONTAL_CENTER,
                        'vertical' => Alignment::VERTICAL_CENTER,
                        'wrapText' => true,
                    ],
                    'fill' => [
                        'fillType' => Fill::FILL_SOLID,
                        'startColor' => [
                            'rgb' => $rowFill,
                        ],
                    ],
                    'borders' => [
                        'allBorders' => [
                            'borderStyle' => Border::BORDER_MEDIUM,
                            'color' => ['rgb' => '000000'],
                        ],
                    ],
                ]);

                $sheet->getStyle(
                    "B{$currentRow}:H{$currentRow}"
                )->getAlignment()
                    ->setHorizontal(
                        Alignment::HORIZONTAL_RIGHT
                    );

                $sheet->getStyle(
                    "B{$currentRow}:H{$currentRow}"
                )->getFont()
                    ->setBold(true);

                $sheet->getRowDimension($currentRow)
                    ->setRowHeight(30);

                $questionRows[] = $currentRow;
                $sectionQuestionRows[] = $currentRow;

                $currentRow++;
            }

            $sectionEndRow = $currentRow - 1;

            if ($sectionEndRow >= $sectionStartRow) {
                /*
                 * Merge section title vertically.
                 */
                $sheet->mergeCells(
                    "I{$sectionStartRow}:J{$sectionEndRow}"
                );

                $sheet->setCellValue(
                    "I{$sectionStartRow}",
                    $section['title'] ?? ''
                );

                $sheet->getStyle(
                    "I{$sectionStartRow}:J{$sectionEndRow}"
                )->applyFromArray([
                    'font' => [
                        'bold' => true,
                        'size' => 11,
                    ],
                    'alignment' => [
                        'horizontal' => Alignment::HORIZONTAL_CENTER,
                        'vertical' => Alignment::VERTICAL_CENTER,
                        'wrapText' => true,
                    ],
                    'fill' => [
                        'fillType' => Fill::FILL_SOLID,
                        'startColor' => [
                            'rgb' => $sectionIndex % 2 === 0
                                ? 'F8CBAD'
                                : 'FFFFFF',
                        ],
                    ],
                    'borders' => [
                        'allBorders' => [
                            'borderStyle' => Border::BORDER_MEDIUM,
                            'color' => ['rgb' => '000000'],
                        ],
                    ],
                ]);

                /*
                 * Merge section average vertically.
                 */
                $sheet->mergeCells(
                    "{$sectionAverageColumnLetter}{$sectionStartRow}:"
                        . "{$sectionAverageColumnLetter}{$sectionEndRow}"
                );

                $sectionAverage =
                    $section['statistics']['average']
                    ?? $this->calculateSectionAverage($section);

                $sheet->setCellValue(
                    "{$sectionAverageColumnLetter}{$sectionStartRow}",
                    is_numeric($sectionAverage)
                        ? $sectionAverage / 5
                        : null
                );

                $sheet->getStyle(
                    "{$sectionAverageColumnLetter}{$sectionStartRow}:"
                        . "{$sectionAverageColumnLetter}{$sectionEndRow}"
                )->applyFromArray([
                    'font' => [
                        'bold' => true,
                    ],
                    'alignment' => [
                        'horizontal' => Alignment::HORIZONTAL_CENTER,
                        'vertical' => Alignment::VERTICAL_CENTER,
                        'textRotation' => 90,
                    ],
                    'fill' => [
                        'fillType' => Fill::FILL_SOLID,
                        'startColor' => [
                            'rgb' => $sectionIndex % 2 === 0
                                ? 'F8CBAD'
                                : 'FFFFFF',
                        ],
                    ],
                    'borders' => [
                        'allBorders' => [
                            'borderStyle' => Border::BORDER_MEDIUM,
                            'color' => ['rgb' => '000000'],
                        ],
                    ],
                ]);

                $sheet->getStyle(
                    "{$sectionAverageColumnLetter}{$sectionStartRow}"
                )->getNumberFormat()
                    ->setFormatCode(
                        NumberFormat::FORMAT_PERCENTAGE_00
                    );
            }
        }

        $questionsEndRow = $currentRow - 1;

        /*
         * Individual response summary.
         */
        $summaryStartRow = $currentRow;

        $sheet->mergeCells(
            "A{$summaryStartRow}:K{$summaryStartRow}"
        );

        $sheet->setCellValue(
            "A{$summaryStartRow}",
            'Average score of each respondent'
        );

        foreach ($responses as $responseIndex => $response) {
            $column = $this->columnLetter(
                $responsesStartColumn + $responseIndex
            );

            $sheet->setCellValue(
                "{$column}{$summaryStartRow}",
                $this->calculateResponseAverage(
                    $sections,
                    $responseIndex
                )
            );
        }

        $summarySecondRow = $summaryStartRow + 1;

        $sheet->mergeCells(
            "A{$summarySecondRow}:K{$summarySecondRow}"
        );

        $sheet->setCellValue(
            "A{$summarySecondRow}",
            'Average score above criteria'
        );

        foreach ($responses as $responseIndex => $response) {
            $column = $this->columnLetter(
                $responsesStartColumn + $responseIndex
            );

            $responseAverage =
                $this->calculateResponseAverage(
                    $sections,
                    $responseIndex
                );

            $sheet->setCellValue(
                "{$column}{$summarySecondRow}",
                is_numeric($responseAverage)
                    ? round($responseAverage - $threshold, 2)
                    : null
            );
        }

        $summaryThirdRow = $summaryStartRow + 2;

        $sheet->mergeCells(
            "A{$summaryThirdRow}:K{$summaryThirdRow}"
        );

        $sheet->setCellValue(
            "A{$summaryThirdRow}",
            'Presence / Absence indicator'
        );

        foreach ($responses as $responseIndex => $response) {
            $column = $this->columnLetter(
                $responsesStartColumn + $responseIndex
            );

            $sheet->setCellValue(
                "{$column}{$summaryThirdRow}",
                $this->countResponseAnswers(
                    $sections,
                    $responseIndex
                ) > 0
                    ? 'P'
                    : 'A'
            );
        }


        $overall = $analysis['overall_statistics'] ?? [];

        $studentsExceedingCriteria = 0;

        foreach ($responses as $responseIndex => $response) {
            $responseAverage = $this->calculateResponseAverage(
                $sections,
                $responseIndex
            );

            if (
                $responseAverage !== null
                && $responseAverage >= $threshold
            ) {
                $studentsExceedingCriteria++;
            }
        }

        $studentsExceedingPercentage = $responsesCount > 0
            ? $studentsExceedingCriteria / $responsesCount
            : 0;

        $sheet->setCellValue(
            "{$averageColumnLetter}{$summaryStartRow}",
            $overall['average'] ?? null
        );

        $sheet->setCellValue(
            "{$exceedingColumnLetter}{$summaryStartRow}",
            'Average satisfaction level'
        );

        $sheet->mergeCells(
            "{$exceedingColumnLetter}{$summaryStartRow}:"
                . "{$sectionAverageColumnLetter}{$summaryStartRow}"
        );

        $sheet->setCellValue(
            "{$averageColumnLetter}{$summarySecondRow}",
            $studentsExceedingCriteria
        );

        $sheet->mergeCells(
            "{$exceedingColumnLetter}{$summarySecondRow}:"
                . "{$sectionAverageColumnLetter}{$summarySecondRow}"
        );

        $sheet->setCellValue(
            "{$exceedingColumnLetter}{$summarySecondRow}",
            'No. respondents exceeding criteria'
        );

        $sheet->setCellValue(
            "{$averageColumnLetter}{$summaryThirdRow}",
            $studentsExceedingPercentage
        );

        $sheet->mergeCells(
