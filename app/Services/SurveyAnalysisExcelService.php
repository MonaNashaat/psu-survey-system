    /**
     * Build charts sheet.
     *
     * Two charts are created for each survey section:
     * 1. Class Average
     * 2. % respondents Exceeding Criteria
     */
    private function buildChartsSheet(
        Worksheet $sheet,
        array $analysis
    ): void {
        $sheet->setRightToLeft(false);
        $sheet->setShowGridlines(false);

        $sections = $analysis['sections'] ?? [];

        /*
    |--------------------------------------------------------------------------
    | Page title
    |--------------------------------------------------------------------------
    */

        $sheet->mergeCells('A1:P1');

        $sheet->setCellValue(
            'A1',
            'COURSE EVALUATION SURVEY CHARTS'
        );

        $sheet->getStyle('A1:P1')
            ->applyFromArray([
                'font' => [
                    'bold' => true,
                    'size' => 16,
                    'color' => [
                        'rgb' => self::WHITE,
                    ],
                ],
                'alignment' => [
                    'horizontal' =>
                    Alignment::HORIZONTAL_CENTER,
                    'vertical' =>
                    Alignment::VERTICAL_CENTER,
                ],
                'fill' => [
                    'fillType' =>
                    Fill::FILL_SOLID,
                    'startColor' => [
                        'rgb' =>
                        self::PRIMARY_BLUE,
                    ],
                ],
            ]);

        $sheet->getRowDimension(1)
            ->setRowHeight(28);

        /*
    |--------------------------------------------------------------------------
    | Data area used by charts
    |--------------------------------------------------------------------------
    |
    | R = Question
    | S = Average
    | T = Satisfaction %
    |
    */

        $questionColumn = 'R';
        $averageColumn = 'S';
        $percentageColumn = 'T';

        $dataRow = 3;

        /*
     * First pair of charts starts from row 3.
     */
        $chartTopRow = 3;

        /*
     * Approximate chart height.
     */
        $chartHeight = 20;

        $chartIndex = 1;

        foreach ($sections as $sectionIndex => $section) {

            /*
         * Numeric questions only.
         */
            $numericQuestions = array_values(
                array_filter(
                    $section['questions'] ?? [],
                    fn(array $question) =>
                    !empty($question['is_numeric'])
                )
            );

            if (empty($numericQuestions)) {
                continue;
            }

            $sectionTitle =
                $section['title']
                ?? 'Section ' . ($sectionIndex + 1);

            /*
        |--------------------------------------------------------------------------
        | Helper data table
        |--------------------------------------------------------------------------
        */

            $sheet->setCellValue(
                "{$questionColumn}{$dataRow}",
                'Question'
            );

            $sheet->setCellValue(
                "{$averageColumn}{$dataRow}",
                'Class Average'
            );

            $sheet->setCellValue(
                "{$percentageColumn}{$dataRow}",
                '% Respondents Exceeding Criteria'
            );

            $sheet->getStyle(
                "{$questionColumn}{$dataRow}:{$percentageColumn}{$dataRow}"
            )->applyFromArray([
                'font' => [
                    'bold' => true,
                ],
                'fill' => [
                    'fillType' =>
                    Fill::FILL_SOLID,
                    'startColor' => [
                        'rgb' =>
                        self::LIGHT_BLUE,
                    ],
                ],
                'borders' => [
                    'allBorders' => [
                        'borderStyle' =>
                        Border::BORDER_THIN,
                        'color' => [
                            'rgb' =>
                            self::BORDER_COLOR,
                        ],
                    ],
                ],
            ]);

            $dataRow++;

            $firstDataRow = $dataRow;

            foreach (
                $numericQuestions as
                $questionIndex => $question
            ) {
                $statistics =
                    $question['statistics'] ?? [];

                $questionNumber =
                    $question['number']
                    ?? ($questionIndex + 1);

                /*
             * Q1, Q2, Q3...
             */
                $sheet->setCellValue(
                    "{$questionColumn}{$dataRow}",
                    'Q' . $questionNumber
                );

                /*
             * Average from 1 to 5.
             */
                $sheet->setCellValue(
                    "{$averageColumn}{$dataRow}",
                    is_numeric(
                        $statistics['average'] ?? null
                    )
                        ? (float) $statistics['average']
                        : 0
                );

                /*
             * Satisfaction percentage from 0 to 100.
             */
                $sheet->setCellValue(
                    "{$percentageColumn}{$dataRow}",
                    is_numeric(
                        $statistics['satisfaction_percentage'] ?? null
                    )
                        ? (float) $statistics['satisfaction_percentage']
                        : 0
                );

                $dataRow++;
            }

            $lastDataRow = $dataRow - 1;

            /*
        |--------------------------------------------------------------------------
        | Categories Q1, Q2, Q3...
        |--------------------------------------------------------------------------
        */

            $categories =
                new DataSeriesValues(
                    DataSeriesValues::DATASERIES_TYPE_STRING,

                    "'Charts'!"
                        . "\${$questionColumn}\${$firstDataRow}:"
                        . "\${$questionColumn}\${$lastDataRow}",

                    null,
                    count($numericQuestions)
                );

            /*
        |--------------------------------------------------------------------------
        | Chart 1: Class Average
        |--------------------------------------------------------------------------
        */

            $averageValues =
                new DataSeriesValues(
                    DataSeriesValues::DATASERIES_TYPE_NUMBER,

                    "'Charts'!"
                        . "\${$averageColumn}\${$firstDataRow}:"
                        . "\${$averageColumn}\${$lastDataRow}",

                    null,
                    count($numericQuestions)
                );

            $averageSeries =
                new DataSeries(
                    DataSeries::TYPE_BARCHART,
                    DataSeries::GROUPING_CLUSTERED,
                    [0],
                    [],
                    [$categories],
                    [$averageValues]
                );

            /*
         * Vertical columns.
         */
            $averageSeries->setPlotDirection(
                DataSeries::DIRECTION_COL
            );

            $averagePlotArea =
                new PlotArea(
                    null,
                    [$averageSeries]
                );

            $averageChart =
                new Chart(
                    'average_chart_' . $chartIndex,
                    new Title(
                        $sectionTitle
                            . ' - Class Average'
                    ),
                    null,
                    $averagePlotArea
                );

            /*
         * Left chart.
         */
            $averageChart->setTopLeftPosition(
                'A' . $chartTopRow
            );

            $averageChart->setBottomRightPosition(
                'H'
                    . (
                        $chartTopRow
                        + $chartHeight
                    )
            );

            $sheet->addChart(
                $averageChart
            );

            /*
        |--------------------------------------------------------------------------
        | Chart 2: % Respondents Exceeding Criteria
        |--------------------------------------------------------------------------
        */

            $percentageValues =
                new DataSeriesValues(
                    DataSeriesValues::DATASERIES_TYPE_NUMBER,

                    "'Charts'!"
                        . "\${$percentageColumn}\${$firstDataRow}:"
                        . "\${$percentageColumn}\${$lastDataRow}",

                    null,
                    count($numericQuestions)
                );

            $percentageSeries =
                new DataSeries(
                    DataSeries::TYPE_BARCHART,
                    DataSeries::GROUPING_CLUSTERED,
                    [0],
                    [],
                    [$categories],
                    [$percentageValues]
                );

            $percentageSeries->setPlotDirection(
                DataSeries::DIRECTION_COL
            );

            $percentagePlotArea =
                new PlotArea(
                    null,
                    [$percentageSeries]
                );

            $percentageChart =
                new Chart(
                    'percentage_chart_' . $chartIndex,
                    new Title(
                        $sectionTitle
                            . ' - % Respondents Exceeding Criteria'
                    ),
                    null,
                    $percentagePlotArea
                );

            /*
         * Right chart.
         */
            $percentageChart->setTopLeftPosition(
                'I' . $chartTopRow
            );

            $percentageChart->setBottomRightPosition(
                'P'
                    . (
                        $chartTopRow
                        + $chartHeight
                    )
            );

            $sheet->addChart(
                $percentageChart
            );

            /*
        |--------------------------------------------------------------------------
        | Next section
        |--------------------------------------------------------------------------
        */

            $chartTopRow +=
                $chartHeight + 2;

            /*
