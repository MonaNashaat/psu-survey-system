        $average = (float) $average;

        return match (true) {
            $average >= 4.5 =>
            'Excellent overall evaluation.',
            $average >= 4.0 =>
            'Very good overall evaluation.',
            $average >= 3.0 =>
            'Acceptable overall evaluation.',
            $average >= 2.0 =>
            'Improvement is recommended.',
