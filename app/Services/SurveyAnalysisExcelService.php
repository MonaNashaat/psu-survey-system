    private function calculateSectionAverage(
        array $section
    ): ?float {
        $averages = [];

        foreach (
            $section['questions'] ?? []
            as $question
        ) {
            if (empty($question['is_numeric'])) {
                continue;
            }

            $average =
                $question['statistics']['average']
                ?? null;

            if (is_numeric($average)) {
                $averages[] = (float) $average;
            }
        }

        if (empty($averages)) {
            return null;
        }

        return round(
            array_sum($averages) / count($averages),
            2
        );
    }
