    /*
    |--------------------------------------------------------------------------
    | إنشاء محور
    |--------------------------------------------------------------------------
    */
    private function createSection(
        int $surveyId,
        string $title,
        int $order
    ): int {
        return DB::table('survey_sections')->insertGetId([
            'survey_id' => $surveyId,
            'title' => $title,
            'display_order' => $order,
            'created_at' => now(),
            'updated_at' => now(),
        ]);
    }

    /*
    |--------------------------------------------------------------------------
    | إنشاء سؤال
    |--------------------------------------------------------------------------
    */
    private function question(
        int $surveyId,
        int $sectionId,
        string $text,
        string $type,
        int $order,
        bool $required = true,
        array $options = []
    ): int {
        $questionId = DB::table('questions')->insertGetId([
            'survey_id' => $surveyId,
            'survey_section_id' => $sectionId,
            'question_text' => $text,
            'type' => $type,
            'is_required' => $required,
            'display_order' => $order,
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        foreach ($options as $index => $option) {
            DB::table('question_options')->insert([
                'question_id' => $questionId,
                'option_text' => $option,

                /*
                 * الـscale فقط يأخذ قيمة رقمية.
                 * mcq و checkbox يعتمدون على option id.
                 */
                'option_value' => $type === 'scale'
                    ? $index + 1
                    : null,

                'display_order' => $index + 1,
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }

        return $questionId;
