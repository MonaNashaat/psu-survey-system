    private function seedTemplate(
        string $name,
        string $description,
        array $sections,
        array $scaleOptions,
        array $textQuestions = [],
        bool $reverseValues = false
    ): void {
        $template = SurveyTemplate::updateOrCreate(
            ['name' => $name],
            [
                'description' => $description,
                'is_active' => true,
            ]
        );

        // حذف القديم وإعادة البناء
        $template->sections()->delete();
        $template->questions()->delete();

        $sectionOrder = 1;

        foreach ($sections as $sectionTitle => $questions) {
            $section = SurveyTemplateSection::create([
                'survey_template_id' => $template->id,
                'title' => $sectionTitle,
                'display_order' => $sectionOrder++,
            ]);

            foreach ($questions as $index => $text) {
                $question = SurveyTemplateQuestion::create([
                    'survey_template_id' => $template->id,
                    'survey_template_section_id' => $section->id,
                    'question_text' => $text,
                    'type' => 'scale',
                    'is_required' => true,
                    'display_order' => $index + 1,
                ]);

                foreach ($scaleOptions as $i => $option) {
                    $value = $reverseValues ? (count($scaleOptions) - $i) : ($i + 1);

                    SurveyTemplateQuestionOption::create([
                        'survey_template_question_id' => $question->id,
                        'option_text' => $option,
                        'option_value' => $value,
                        'display_order' => $i + 1,
                    ]);
                }
            }
        }

        foreach ($textQuestions as $index => $textQuestion) {
            SurveyTemplateQuestion::create([
                'survey_template_id' => $template->id,
                'survey_template_section_id' => null,
                'question_text' => $textQuestion,
                'type' => 'text',
                'is_required' => false,
                'display_order' => 999 + $index,
            ]);
        }
    }
